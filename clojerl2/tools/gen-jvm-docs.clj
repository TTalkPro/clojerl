;; Writes priv/clj2/jvm-docs.eterm: the docstrings and arglists of JVM
;; Clojure's public vars in the namespaces clojerl2 provides, so (doc map),
;; (:doc (meta #'map)) and :arglists read as on the JVM where clojerl2's own
;; definition has none. The text is Clojure's (EPL-1.0).
;;   clojure -Sdeps '{:deps {org.clojure/clojure {:mvn/version "1.12.4"}}}' -M tools/gen-jvm-docs.clj
(require '[clojure.string :as str])
(def nss '[clojure.core clojure.string clojure.set clojure.walk clojure.edn clojure.math
           clojure.template clojure.test clojure.repl clojure.pprint clojure.zip clojure.data])
(defn esc [s]
  (-> s (str/replace "\\" "\\\\") (str/replace "\"" "\\\"") (str/replace "\n" "\\n")
      (str/replace "\t" "\\t") (str/replace "\r" "\\r")))
(defn bin [s] (str "<<\"" (esc s) "\"/utf8>>"))
(with-open [w (clojure.java.io/writer "priv/clj2/jvm-docs.eterm")]
  (.write w (str "%% Docstrings and arglists of JVM Clojure " (clojure-version)
                 "'s public vars (EPL-1.0), generated by tools/gen-jvm-docs.clj.\n"
                 "%% {Ns, Name, Doc | nil, Arglists (printed) | nil}.\n"))
  (doseq [n nss]
    (try (require n) (catch Throwable _ nil))
    (when-let [ns (find-ns n)]
      (doseq [[s v] (sort-by (comp str key) (ns-publics ns))]
        (let [{:keys [doc arglists]} (meta v)]
          (when (or doc arglists)
            (.write w (str "{'" n "', " (bin (str s)) ", "
                           (if doc (bin doc) "nil") ", "
                           (if arglists (bin (pr-str arglists)) "nil") "}.\n"))))))))
